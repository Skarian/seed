import { test, expect } from './fixtures.js';
test.use({extraHTTPHeaders:{Origin:'http://127.0.0.1:4311'}});

test('clears finished activity across reloads, preserves queued work and shows new events',async({page,request},testInfo)=>{
  const offer=(await (await request.get('/api/v1/pool/offers?worker_class=image')).json()).items[0];
  const launch=await request.post('/api/v1/pool/launch',{headers:{'Idempotency-Key':crypto.randomUUID()},data:{selections:[{offer_id:offer.id,quantity:1}],max_hourly:offer.hourly}});
  expect(launch.ok()).toBe(true);
  const worker=(await launch.json()).workers[0];
  await request.post(`/api/v1/pool/workers/${worker.id}/actions`,{data:{action:'quit'}});
  await expect.poll(async()=>(await (await request.get('/api/v1/pool')).json()).workers.find((w:any)=>w.id===worker.id)?.state).toBe('released');
  const imported=await request.post('/api/v1/admin/loras/import',{data:{version_id:11,mode:'sfw',name:'Activity test adapter',description:'Keep this adapter',default_scale:1,trigger_words:[],files:[{file_id:30,route:'fl'}]}});
  expect(imported.status()).toBe(202);
  const requestBody={workflow:'text-to-image',prompt:'Keep queued generation',mode:'sfw',output:{aspect:'16:9',size:'1mp'},seed:'1',count:1};
  const submit=async(prompt:string)=>{
    const response=await request.post('/api/v1/jobs',{headers:{'Idempotency-Key':crypto.randomUUID()},data:{...requestBody,prompt}});
    expect(response.status()).toBe(202);return (await response.json()).jobs[0];
  };
  const finished=await submit('Finished activity fixture'),queued=await submit('Keep queued generation');
  await request.post(`/api/v1/jobs/${finished.id}/cancel`,{data:{}});
  const assetsBefore=await (await request.get('/api/v1/assets')).json();
  await page.goto('/');await page.getByRole('button',{name:/^Activity/}).click();
  const modal=page.getByRole('dialog',{name:'Activity',exact:true});
  await expect(modal.getByText('Finished activity fixture',{exact:true})).toBeVisible();
  await expect(modal.getByRole('region',{name:'LoRA import: Activity test adapter'})).toBeVisible();
  await expect(modal.locator('.worker-activity')).toHaveCount(1);
  await page.route('**/api/v1/activity/clear',route=>route.fulfill({status:503,json:{error:{message:'Could not clear activity. Try again.'}}}));
  await modal.getByRole('button',{name:'Clear activity',exact:true}).click();
  await expect(modal.getByRole('alert')).toHaveText('Could not clear activity. Try again.');
  await expect(modal.getByText('Finished activity fixture',{exact:true})).toBeVisible();
  await page.unroute('**/api/v1/activity/clear');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:testInfo.outputPath('clear-activity-mobile.png')});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await modal.getByRole('button',{name:'Clear activity',exact:true}).click();
  await expect(modal.getByRole('status')).toHaveText('Finished activity cleared.');
  await expect(modal.getByText('Finished activity fixture',{exact:true})).toHaveCount(0);
  await expect(modal.getByText('Keep queued generation',{exact:true})).toBeVisible();
  await expect(modal.locator('.import-activity,.worker-activity')).toHaveCount(0);
  await expect(modal.getByRole('button',{name:'Clear activity',exact:true})).toBeDisabled();
  expect((await (await request.get(`/api/v1/jobs/${queued.id}`)).json()).state).toBe('queued');
  expect((await (await request.get(`/api/v1/jobs/${finished.id}`)).json()).state).toBe('cancelled');
  expect((await (await request.get('/api/v1/pool')).json()).workers.some((w:any)=>w.id===worker.id)).toBe(true);
  expect((await (await request.get('/api/v1/admin/loras')).json()).items.some((l:any)=>l.name==='Activity test adapter')).toBe(true);
  expect(await (await request.get('/api/v1/assets')).json()).toEqual(assetsBefore);
  await page.reload();await page.getByRole('button',{name:'Toggle sidebar',exact:true}).click();await page.getByRole('button',{name:/^Activity/}).click();
  await expect(modal.getByText('Keep queued generation',{exact:true})).toBeVisible();
  await expect(modal.getByText('Finished activity fixture',{exact:true})).toHaveCount(0);
  await request.post(`/api/v1/jobs/${queued.id}/cancel`,{data:{}});
  await expect(modal.getByRole('button',{name:'Clear activity',exact:true})).toBeEnabled();
  await modal.getByRole('button',{name:'Clear activity',exact:true}).click();
  await expect(modal.getByText('No activity yet.',{exact:true})).toBeVisible();
  const newJob=await submit('New activity after clearing');
  await expect(modal.getByText('New activity after clearing',{exact:true})).toBeVisible();
  await request.post(`/api/v1/jobs/${newJob.id}/cancel`,{data:{}});
});
