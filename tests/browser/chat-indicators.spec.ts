import {test,expect} from '@playwright/test';
test('sidebar switches from working spinner to persistent unread dot',async({page})=>{
 await page.addInitScript(()=>{(window as any).EventSource=class {close(){}};});
 const chat:any={id:'indicator',title:'A forest at dawn',mode:'sfw',workflow:null,version:0,activity:'thinking',reasoning:true,last_reply_id:'',messages:[],groups:[],assets:[],jobs:[],accounting:[]};
 await page.route('**/api/v1/chats**',r=>r.fulfill({json:new URL(r.request().url()).pathname==='/api/v1/chats'?{items:[chat]}:chat}));
 await page.goto('/chat');
 const row=page.getByRole('button',{name:'Open chat: A forest at dawn'});
 await expect(row.getByRole('status',{name:'Working'})).toBeVisible();
 await expect(row).not.toContainText('thinking');
 chat.activity='idle';chat.last_reply_id='answer';chat.messages=[{id:'answer',role:'assistant',text:'Ready to create.',assets:[]}];
 await expect(row.locator('.chat-unread')).toBeVisible();
 await page.reload();await expect(row.locator('.chat-unread')).toBeVisible();
 await page.screenshot({path:'.local/qa-sidebar-unread.png'});
 await row.click();await expect(row.locator('.chat-unread')).toHaveCount(0);
 await page.reload();await expect(row.locator('.chat-unread')).toHaveCount(0);
 chat.activity='generating';await expect(row.locator('.chat-working')).toBeVisible();
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Toggle sidebar'}).click();
 await expect(row.locator('.chat-working')).toBeVisible();
 await page.screenshot({path:'.local/qa-sidebar-working-mobile.png'});
});
