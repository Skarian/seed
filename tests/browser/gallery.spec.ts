import { test, expect } from '@playwright/test';
import sharp from 'sharp';
test('gallery respects available slots, NSFW opt-in, and reuses saved assets', async ({page}) => {
  const image=await sharp({create:{width:64,height:48,channels:3,background:'#b59171'}}).png().toBuffer();
  await page.route('**/api/v1/assets?*',r=>r.fulfill({json:{items:[1,2,3].map(n=>({id:'saved-'+n,kind:'image',name:'Image '+n,mode:n===3?'nsfw':'sfw'})),next_cursor:null}}));
  await page.route('**/api/v1/assets/saved-*/content',r=>r.fulfill({contentType:'image/png',body:image}));
  await page.route('**/api/v1/assets/saved-*',r=>r.fulfill({json:{mime_type:'image/png'}}));
  await page.goto('/');
  await page.getByLabel('Workflow').selectOption('image-to-image');
  await page.getByRole('button',{name:'Gallery',exact:true}).click();
  const picker=page.getByRole('dialog',{name:'Choose from gallery'});
  await expect(picker).toContainText('max: 2');
  await expect(picker.getByRole('button',{name:'Select Image 3'})).toHaveCount(0);
  await picker.getByLabel('Show NSFW').check();
  await picker.getByRole('button',{name:'Select Image 1'}).click();
  await picker.getByRole('button',{name:'Select Image 2'}).click();
  await expect(picker.getByRole('button',{name:'Select Image 3'})).toBeDisabled();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'.local/gallery-mobile.png'});
  await picker.getByRole('button',{name:'Select (2)',exact:true}).click();
  await expect(page.getByRole('button',{name:'Preview Image 1'})).toBeVisible();
  await expect(page.getByRole('button',{name:'Preview Image 2'})).toBeVisible();
  await page.getByRole('button',{name:'Gallery',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('2 already added');
  await expect(page.getByRole('button',{name:'Select Image 1'})).toBeDisabled();
});

test('gallery video references submit existing IDs without uploading duplicates', async ({page}) => {
  const image=await sharp({create:{width:64,height:48,channels:3,background:'#467850'}}).png().toBuffer();
  await page.route('**/api/v1/assets?*',r=>r.fulfill({json:{items:[{id:'saved-image',kind:'image',name:'Saved image',mode:'sfw'}],next_cursor:null}}));
  await page.route('**/api/v1/assets/saved-image',r=>r.fulfill({json:{mime_type:'image/png'}}));
  await page.route('**/api/v1/assets/saved-image/content',r=>r.fulfill({contentType:'image/png',body:image}));
  await page.route('**/api/v1/studio',r=>r.fulfill({json:{worker:{state:'ready',stale:false,connected:true},queue:{paused:false,active:0,waiting:0},implementation:{generation:true}}}));
  await page.route('**/api/v1/capabilities',r=>r.fulfill({json:{revision:'test',workflows:{'reference-to-video':{enabled:true,modes:['sfw','nsfw']}}}}));
  await page.route('**/api/v1/jobs',r=>r.fulfill({json:r.request().method()==='POST'?{submission_id:'test',jobs:[]}:{items:[]}}));
  let uploads=0; page.on('request',r=>{if(r.url().includes('/api/v1/uploads'))uploads++;});
  await page.goto('/');
  await page.getByLabel('Workflow').selectOption('reference-to-video');
  await page.getByRole('button',{name:'Gallery',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('max: 12');
  await page.getByRole('button',{name:'Select Saved image'}).click();
  await page.getByRole('button',{name:'Select (1)',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByLabel('Prompt',{exact:true}).fill('Animate this scene');
  const sent=page.waitForRequest(r=>r.url().endsWith('/api/v1/jobs')&&r.method()==='POST');
  await page.getByRole('button',{name:'Create video'}).click();
  expect((await sent).postDataJSON().references[0]).toMatchObject({asset_id:'saved-image',kind:'image'});
  expect(uploads).toBe(0);
});
