import {test,expect} from '@playwright/test';
import fs from 'node:fs/promises';
import {createRequire} from 'node:module';
import {execFileSync} from 'node:child_process';

test('duplicate clips keep separate labels through reorder/removal and source soundtrack mentions',async({page})=>{
 await fs.mkdir('.local/request-instance-preview',{recursive:true});
 const fixture='.local/request-instance-preview/source.mp4';
 execFileSync(createRequire(import.meta.url)('ffmpeg-static'),['-hide_banner','-loglevel','error','-nostdin','-y','-f','lavfi','-i','testsrc2=size=480x270:rate=12','-t','6','-c:v','libx264','-pix_fmt','yuv420p',fixture],{windowsHide:true,timeout:30000});
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
 const references=[
  {id:'opening-clip',asset_id:'source-video',kind:'video',role:'reference',include_audio:true,range:{start_seconds:0,duration_seconds:3}},
  {id:'ending-clip',asset_id:'source-video',kind:'video',role:'reference',include_audio:true,range:{start_seconds:3,duration_seconds:3}},
 ];
 const assets=[{id:'source-video',kind:'video',name:'Two moments.mp4',note:'Same file, different clips.',metadata:{duration:6,width:480,height:270}}];
 const request={workflow:'reference-to-video',mode:'sfw',prompt:'Follow <Video 1> with <Audio 1>, then <Video 2> with <Audio 2>.',count:1,seed:'42',output:{aspect:'16:9',size:'native',duration_seconds:5},references};
 const chat={id:'instances',title:'Instance identity',mode:'sfw',workflow:'reference-to-video',version:0,epoch:0,activity:'idle',reasoning:true,assets:['source-video'],asset_manifest:assets,jobs:[],messages:[],groups:[{id:'group',state:'reviewing',cards:[{id:'card',workflow:'reference-to-video',revisions:[{number:1,request,decision:'undecided',job_ids:[],notes:{}}]}]}]};
 await page.route('**/api/v1/chat-config',r=>r.fulfill({json:{configured:true}}));
 await page.route('**/api/v1/chats**',r=>r.fulfill({json:new URL(r.request().url()).pathname==='/api/v1/chats'?{items:[]}:chat}));
 await page.route('**/api/v1/assets/source-video',r=>r.fulfill({json:{...assets[0],duration:6,mime_type:'video/mp4'}}));
 await page.route('**/api/v1/assets/source-video/content',async r=>r.fulfill({contentType:'video/mp4',body:await fs.readFile(fixture)}));
 await page.setViewportSize({width:1200,height:1000});await page.goto('/chat?chat=instances');
 await page.getByRole('button',{name:'Review / history',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'Review generation'}),editor=dialog.getByRole('combobox',{name:'Prompt'});
 await expect(dialog.locator('.request-input-row')).toHaveCount(2);
 await expect(editor).toHaveText('Follow Video 1 with Audio 1, then Video 2 with Audio 2.');
 await dialog.locator('.request-input-row').nth(1).getByRole('button',{name:'Preview Video 2'}).click();
 await expect(page.getByRole('navigation',{name:'Input navigation'})).toContainText('2 of 2');
 await expect(page.locator('.viewer-reference-label')).toHaveText('Video 2');
 await expect(page.locator('.viewer-input-range')).toContainText('3–6 seconds');
 await page.getByRole('button',{name:'Previous input'}).click();
 await expect(page.getByRole('navigation',{name:'Input navigation'})).toContainText('1 of 2');
 await expect(page.locator('.viewer-reference-label')).toHaveText('Video 1');
 await expect(page.locator('.viewer-input-range')).toContainText('0–3 seconds');
 await expect(page.locator('.viewer-canvas video')).toHaveJSProperty('duration',6);
 await page.screenshot({path:'.local/request-instance-preview/first-clip.png'});
 await page.getByRole('button',{name:'Next input'}).click();
 await page.screenshot({path:'.local/request-instance-preview/second-clip.png'});
 await page.getByRole('button',{name:'Close preview',exact:true}).click();
 // The director can add another instance of a file already used twice.
 await dialog.getByRole('button',{name:'+ Add input',exact:true}).click();
 await page.getByRole('dialog',{name:'Add input',exact:true}).getByRole('button',{name:'Video Two moments.mp4',exact:true}).click();
 await expect(dialog.locator('.request-input-row')).toHaveCount(3);
 await dialog.getByRole('button',{name:'Edit Video 3',exact:true}).click();
 const added=dialog.locator('.request-input-row').nth(2);
 await added.getByLabel('Start time (sec)',{exact:true}).fill('2');
 await added.getByLabel('Clip length (sec)',{exact:true}).fill('2');
 await added.getByLabel('Include source audio',{exact:true}).check();
 await expect(editor).toHaveText('Follow Video 1 with Audio 1, then Video 2 with Audio 2.');
 await added.getByRole('button',{name:'Preview Video 3',exact:true}).click();
 await expect(page.locator('.viewer-reference-label')).toHaveText('Video 3');
 await expect(page.getByRole('navigation',{name:'Input navigation'})).toContainText('3 of 3');
 await expect(page.locator('.viewer-input-range')).toContainText('2–4 seconds');
 await page.getByRole('button',{name:'Close preview',exact:true}).click();
 await dialog.getByLabel('More options for Video 3').click();await dialog.getByRole('button',{name:'Move up',exact:true}).click();
 await expect(editor).toHaveText('Follow Video 1 with Audio 1, then Video 3 with Audio 3.');
 await expect(dialog.locator('.request-input-row').nth(1)).toContainText('2–4 sec');
 await dialog.getByLabel('More options for Video 2').click();await dialog.getByRole('button',{name:'Remove',exact:true}).click();
 await expect(editor).toHaveText('Follow Video 1 with Audio 1, then Video 2 with Audio 2.');
 await dialog.getByLabel('More options for Video 2').click();await dialog.getByRole('button',{name:'Move up',exact:true}).click();
 await expect(editor).toHaveText('Follow Video 2 with Audio 2, then Video 1 with Audio 1.');
 await expect(dialog.locator('.request-input-row').first()).toContainText('3–6 sec');
 await dialog.getByLabel('More options for Video 2').click();await dialog.getByRole('button',{name:'Remove',exact:true}).click();
 await expect(editor.locator('.missing')).toHaveCount(2);
 await expect(dialog.getByRole('button',{name:'Save changes'})).toBeDisabled();
 await dialog.getByRole('button',{name:'Close review'}).click();
 await page.getByRole('button',{name:'Review / history',exact:true}).click();
 await dialog.getByRole('button',{name:/Provide feedback/}).click();
 const composer=page.getByRole('combobox',{name:'Chat message'});await composer.fill('Use @');
 await expect(page.getByRole('option').filter({hasText:'Audio 1'})).toHaveCount(1);
 await expect(page.getByRole('option').filter({hasText:'Audio 2'})).toHaveCount(1);
 await page.getByRole('option').filter({hasText:'Audio 2'}).click();
 await expect(composer.locator('.input-mention')).toHaveText('Audio 2');
 expect(await composer.locator('.input-mention').getAttribute('data-command')).toBe('[Audio 2](asset:source-video)');
 expect(errors).toEqual([]);
});

